// Checks the pairings the design relies on against WCAG 2.2, straight from
// styles/tokens.css, and writes docs/design-system/contrast-report.md.
// Exit code 1 if any pairing is under its bar.
import { readFileSync, writeFileSync } from "node:fs";

const css = readFileSync("styles/tokens.css", "utf8");
const token = (name) => {
  const match = css.match(new RegExp(`--${name}:\\s*(#[0-9a-fA-F]{6})\\b`));
  if (!match) throw new Error(`--${name} is not a six-digit hex in styles/tokens.css`);
  return match[1].toLowerCase();
};
const luminance = (hex) => {
  const [r, g, b] = [1, 3, 5]
    .map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

// [foreground, background, minimum, what it is used for]
const PAIRS = [
  ["ink", "bg", 7, "running text"],
  ["ink", "surface", 7, "running text on a tone-step section"],
  ["muted", "bg", 4.5, "secondary notes"],
  ["muted", "surface", 4.5, "secondary notes on a tone-step section"],
  ["accent", "bg", 3, "the button against the page"],
  ["accent", "surface", 3, "the button and the price block against a tone-step section"],
  ["accent-ink", "accent", 4.5, "the button label and the price"],
  ["accent-ink", "accent-strong", 4.5, "the button label on hover"],
  ["inv-ink", "inv-bg", 7, "the closing section"],
  ["inv-muted", "inv-bg", 4.5, "the legal line"],
  ["inv-bg", "inv-ink", 4.5, "the ink button's label"],
];

let failed = 0;
const rows = PAIRS.map(([fg, bg, min, use]) => {
  const value = ratio(token(fg), token(bg));
  const ok = value >= min;
  if (!ok) failed++;
  return `| \`--${fg}\` on \`--${bg}\` | ${token(fg)} on ${token(bg)} | ${value.toFixed(2)} | ${min} | ${ok ? "pass" : "**FAIL**"} | ${use} |`;
});

const report = [
  "# Contrast report",
  "",
  "Generated by `npm run check:contrast` from `styles/tokens.css`. Do not edit by hand.",
  "",
  "| Pairing | Colours | Ratio | Minimum | Result | Use |",
  "|---|---|---:|---:|---|---|",
  ...rows,
  "",
].join("\n");
writeFileSync("docs/design-system/contrast-report.md", report);
console.log(report);
if (failed) {
  console.error(`${failed} pairing(s) under the bar.`);
  process.exit(1);
}

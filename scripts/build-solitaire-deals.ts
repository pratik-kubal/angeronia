// Prove the deals Solitaire (/solitaire) hands out winnable: seeds from --from upward are dealt
// (lib/solitaire/deal.ts) and searched by lib/solitaire/solver.ts within --budget positions each;
// a seed is kept only once its solution, replayed move by move through the game's own reducer,
// ends in a win, so the bank can only ever hold winnable deals. Writes lib/solitaire/deals.ts
// (committed). Rerun it after changing DEAL_VERSION (the bank is void after it).
//
// Usage: pnpm solitaire:deals [--count=1000] [--budget=250000] [--from=1]

import fs from "node:fs";
import { DEAL_VERSION, deal } from "../lib/solitaire/deal";
import { replay } from "../lib/solitaire/game";
import { solve } from "../lib/solitaire/solver";

const OUT = "lib/solitaire/deals.ts";

function flag(name: string, fallback: number): number {
  const arg = process.argv.find((a) => a.startsWith(`--${name}=`));
  const value = arg ? Number(arg.slice(name.length + 3)) : fallback;
  if (!Number.isInteger(value) || value < 1) throw new Error(`--${name} must be a positive integer`);
  return value;
}

const count = flag("count", 1000);
const budget = flag("budget", 250_000);
const from = flag("from", 1);

const seeds: number[] = [];
const started = Date.now();
let tried = 0;
for (let seed = from; seeds.length < count; seed++) {
  tried++;
  const result = solve(deal(seed), { maxNodes: budget });
  if (result.status !== "won") continue;
  const { state, applied } = replay(seed, result.moves);
  if (applied !== result.moves.length || state.status !== "won") {
    throw new Error(`Seed ${seed}: the solver's win doesn't replay (${applied}/${result.moves.length} moves legal)`);
  }
  seeds.push(seed);
  if (seeds.length % 100 === 0) {
    const s = Math.round((Date.now() - started) / 1000);
    console.log(`${seeds.length}/${count} proven (${tried} tried, ${Math.round((100 * seeds.length) / tried)}%), ${s}s`);
  }
}

const rows: string[] = [];
for (let i = 0; i < seeds.length; i += 16) rows.push(`  ${seeds.slice(i, i + 16).join(", ")},`);
fs.writeFileSync(
  OUT,
  `// GENERATED by scripts/build-solitaire-deals.ts (pnpm solitaire:deals): do not edit by hand.
// Deal seeds proven winnable: each one's solver solution replayed through the reducer to a win
// (${seeds.length} of seeds ${from}–${seeds[seeds.length - 1]}, ${budget.toLocaleString("en-US")} positions searched at most per seed).

/** The DEAL_VERSION the bank was proven under (lib/solitaire/deal.ts). */
export const BANK_DEAL_VERSION = ${DEAL_VERSION};
/** The solver's budget per seed when the bank was proven. */
export const BANK_BUDGET = ${budget};

export const DEALS: readonly number[] = [
${rows.join("\n")}
];
`,
);
console.log(`${seeds.length} winnable deals of ${tried} tried → ${OUT}`);
